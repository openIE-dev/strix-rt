#!/bin/sh
# Kitten TTS end-to-end: Rust ktts (2 runs x 8 reps, rep1 cold), perf level high, then restore auto.
# Waits for GPU idle up to MAXWAIT s (other workers loop pf_* jobs), then runs anyway and reports contention.
cd ~/strix-rt; D=/sys/class/drm/card1/device
G=$MODELS/kitten2/hf/cpp/model-tq2_1.gguf; V=$MODELS/kitten2/hf/cpp/default/voices.json
TXT="Hello from the Framework Desktop. This voice is generated by a ternary speech model."
# exclusive GPU lock (logs/gpu_lock.sh): re-run this whole script under /tmp/strix-gpu.lock
[ -n "$STRIX_GPU_LOCK_HELD" ] || exec ~/strix-rt/logs/gpu_lock.sh sh "$0" "$@"
busy() { false; }  # nobody else can hold the GPU while we hold the lock
echo "[waited ${STRIX_GPU_LOCK_WAITED:-0}s for GPU lock; $(date +%T)]"
echo high | sudo tee $D/power_dpm_force_performance_level >/dev/null
for i in 1 2; do KT_DUMP_PROMPT=logs/kt/rs_prompt.json ./target/release/ktts $G $MODELS/kitten2/rt/decoder $V Bruno "$TXT" logs/kt/rs_e2e.wav 8; echo "[busy now: $(busy && echo YES || echo no)]"; done
echo auto | sudo tee $D/power_dpm_force_performance_level >/dev/null
echo "restored $(cat $D/power_dpm_force_performance_level); other GPU job at end: $(busy && echo YES || echo no) $(date +%T)"
