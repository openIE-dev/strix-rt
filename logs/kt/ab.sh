#!/bin/sh
# A/B env settings on ktts warm LM/decoder (reps 2-5), alternating, after waiting for an idle GPU. usage: ab.sh "ENV_A" "ENV_B"
cd ~/strix-rt; D=/sys/class/drm/card1/device; G=$MODELS/kitten2/hf/cpp/model-tq2_1.gguf; V=$MODELS/kitten2/hf/cpp/default/voices.json
TXT="Hello from the Framework Desktop. This voice is generated by a ternary speech model."
# exclusive GPU lock (logs/gpu_lock.sh): re-run this whole script under /tmp/strix-gpu.lock
[ -n "$STRIX_GPU_LOCK_HELD" ] || exec ~/strix-rt/logs/gpu_lock.sh sh "$0" "$@"
busy() { false; }  # nobody else can hold the GPU while we hold the lock
echo "[waited ${STRIX_GPU_LOCK_WAITED:-0}s for GPU lock; $(date +%T)]"
echo high | sudo tee $D/power_dpm_force_performance_level >/dev/null
for round in 1 2; do for cfg in "$1" "$2"; do echo "== $cfg"; env $cfg ./target/release/ktts $G $MODELS/kitten2/rt/decoder $V Bruno "$TXT" /tmp/ab.wav 5 2>&1 | grep "^rep [2-5]" | cut -d\| -f2,3; cmp -s /tmp/ab.wav.tokens.json logs/kt/rs_e2e.wav.tokens.json && echo tokens_identical; done; done
echo auto | sudo tee $D/power_dpm_force_performance_level >/dev/null; echo "[busy end=$(busy && echo YES || echo no)]"
