# compare Rust kttext vs fork kitten-tts --frontend (normalize=false: rules + chunking, FST backend off); also show FST-on output
import json, subprocess, os
H = os.path.expanduser("~")
long = ("The quick brown fox jumps over the lazy dog. " * 6 + "Then, quite suddenly, everything changed; the sky darkened — and the rain came. ") * 3
T = ["Hello from the Framework Desktop. This voice is generated by a ternary speech model.",
     "hello there...  it is v1.2.3 (really) -- ok", "Wait.what?Really!Yes", "I scored 3 ! Then 4?", "a . . . b", "Bullets: \u2022 one \u2022 two \u2192 three",
     "[excited] Wow, that is great! <laugh> (((really))) yes", "Line one\n\nLine two\n  Line three", "the angle \u03b1 + \u03b2 = \u03c0", "Use [this] or <that> (maybe), ok",
     "  trailing dash -", "ends with colon:", "\"Quoted,\" she said\u2014then left.", "x \u2013 y \u2014 z -- w", "…and so on", long,
     "Short one. " + "A much longer sentence that goes on and on, with commas, and clauses; and more clauses, until it exceeds the limit by quite a lot of characters indeed. " * 4]
inp = "\n".join(json.dumps({"text": t, "normalize": False}) for t in T) + "\n"
fk = subprocess.run([H + "/src/kitten-cpp/build/bin/kitten-tts", "--frontend", "--data", "/tmp/ktp"], input=inp, capture_output=True, text=True).stdout.splitlines()
rs = subprocess.run([H + "/strix-rt/target/release/kttext"], input=inp, capture_output=True, text=True).stdout.splitlines()
ok = 0
for t, a, b in zip(T, fk, rs):
    a, b = json.loads(a), json.loads(b)
    if a == b: ok += 1
    else: print("MISMATCH", repr(t[:80]), "\n fork", a, "\n rust", b)
print(f"{ok}/{len(T)} identical (rules + chunking, FST backend off)")
inp2 = "\n".join(json.dumps({"text": t}) for t in ["I scored 3 ! Then 4?", "It costs $5.50 on Jan 3, 2024 at 10:30am, 25% off.", "Dr. Smith lives at 221B Baker St."]) + "\n"
for l in subprocess.run([H + "/src/kitten-cpp/build/bin/kitten-tts", "--frontend", "--data", "/tmp/ktp"], input=inp2, capture_output=True, text=True).stdout.splitlines(): print("FST on:", json.loads(l)["normalized"])
