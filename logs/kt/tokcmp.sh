#!/bin/bash
# compare Rust tokenizer (kttok) vs llama-tokenize (parse_special) on test strings
cd ~/strix-rt
G=$MODELS/kitten2/hf/cpp/model-tq2_1.gguf
LT=~/src/kitten-cpp/build/bin/llama-tokenize
ok=0; bad=0
while IFS= read -r s; do
  r=$(./target/release/kttok $G "$s" | tr -d ' ')
  l=$($LT -m $G -p "$s" --ids --no-bos --log-disable 2>/dev/null | tail -1 | tr -d ' ')
  if [ "$r" == "$l" ]; then ok=$((ok+1)); else bad=$((bad+1)); echo "MISMATCH: [$s]"; echo " rust  $r"; echo " llama $l"; fi
done <<'T'
Hello from the Framework Desktop. This voice is generated by a ternary speech model.
When the Western music overwhelms the Chinese music, it evokes the long history of conflict between Asia and the Western nations that sought to exploit and dominate it.
I'm sure they'll say we've done it, isn't it? You'd think so.
Numbers: 12345 and 3.14159, plus $100,000!!!
  leading spaces and   multiple   gaps  
Line one.
Line two.

Para three.
Ünïcödé café naïve — “quotes” and ‘single’ …
{emo: 1} Hello there.
email me at test@example.com, or call (555) 123-4567.
Tabs	and	more	tabs.
日本語のテキストも少し。
T
echo "ok=$ok bad=$bad"
