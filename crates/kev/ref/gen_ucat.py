# Generates src/ucat.rs: sorted ranges for Unicode general categories L* | M* (letters+marks) and N*.
import unicodedata, sys
def ranges(pred):
    out=[];s=None
    for c in range(0x110000):
        ok=pred(unicodedata.category(chr(c)))
        if ok and s is None: s=c
        if not ok and s is not None: out.append((s,c-1)); s=None
    if s is not None: out.append((s,0x10FFFF))
    return out
l=ranges(lambda k:k[0]=="L"); lm=ranges(lambda k:k[0] in "LM"); n=ranges(lambda k:k[0]=="N")
f=open("src/ucat.rs","w")
f.write(f"//! Generated by ref/gen_ucat.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
for nm,r in (("L",l),("LM",lm),("N",n)):
    f.write(f"pub static {nm}: [(u32, u32); {len(r)}] = [\n"+"".join(f"(0x{a:X},0x{b:X}),\n" for a,b in r)+"];\n")
f.write("fn has(t: &[(u32, u32)], c: char) -> bool { let c = c as u32; t.binary_search_by(|&(a, b)| if b < c { std::cmp::Ordering::Less } else if a > c { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }).is_ok() }\n")
f.write("/// \\\\p{L}\npub fn is_l(c: char) -> bool { (c as u32) < 0x80 && c.is_ascii_alphabetic() || (c as u32) >= 0x80 && has(&L, c) }\n/// \\\\p{L} | \\\\p{M}\npub fn is_lm(c: char) -> bool { (c as u32) < 0x80 && c.is_ascii_alphabetic() || (c as u32) >= 0x80 && has(&LM, c) }\n/// \\\\p{N}\npub fn is_n(c: char) -> bool { (c as u32) < 0x80 && c.is_ascii_digit() || (c as u32) >= 0x80 && has(&N, c) }\n")
print(unicodedata.unidata_version,len(l),len(lm),len(n))
